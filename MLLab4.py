"""Feature scaling is important before PCA because PCA is affected by the scale of the variables. A feature with a larger numerical range can dominate the principal components. Standardization puts the numerical features on a comparable scale."""

# Apply PCA
from sklearn.decomposition import PCA

pca = PCA()
X_pca_all = pca.fit_transform(X_scaled)

explained_variance = pca.explained_variance_ratio_
cumulative_variance = np.cumsum(explained_variance)

print("Principal components shape:", X_pca_all.shape)

print("\nExplained variance ratio:")
for i, value in enumerate(explained_variance, start=1):
    print(f"PC{i}: {value:.4f}")

print("\nCumulative explained variance:")
for i, value in enumerate(cumulative_variance, start=1):
    print(f"PC{i}: {value:.4f}")

# Display PCA component loadings
components = pd.DataFrame(
    pca.components_,
    columns=numerical_features,
    index=[f'PC{i}' for i in range(1, len(numerical_features) + 1)]
)

display(components)

#2

"""The table above displays the principal component loadings, the explained variance ratio is shown for every component, and the cumulative explained variance shows how much total variance is retained as components are added."""

# Scree plot
plt.figure(figsize=(8, 5))

