"""**a. What changes are observed?**  
The minority class is increased until the two classes are balanced.

**b. Advantage and disadvantage:**  
- Advantage: Random Oversampling keeps the original majority-class observations and balances the classes.
- Disadvantage: It duplicates minority-class observations, which may increase the risk of overfitting.
"""

# Random Undersampling
from imblearn.under_sampling import RandomUnderSampler

rus = RandomUnderSampler(random_state=42)

