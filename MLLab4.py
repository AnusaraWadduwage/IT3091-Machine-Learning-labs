# Prepare X and y for feature selection
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score

X = df.drop('survived', axis=1)
y = df['survived']

X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training shape:", X_train.shape)
print("Testing shape:", X_test.shape)

# Forward Feature Selection
remaining_features = list(X_train.columns)
selected_features = []
selection_results = []

while remaining_features:
    best_feature = None
    best_accuracy = -1

    for feature in remaining_features:
        current_features = selected_features + [feature]

        model = LogisticRegression(max_iter=1000, random_state=42)
        model.fit(X_train[current_features], y_train)

        predictions = model.predict(X_test[current_features])
        accuracy = accuracy_score(y_test, predictions)

        if accuracy > best_accuracy:
            best_accuracy = accuracy
            best_feature = feature

    selected_features.append(best_feature)
    remaining_features.remove(best_feature)

    selection_results.append({
        'Step': len(selected_features),
        'Feature': best_feature,
        'Accuracy': best_accuracy
    })

selection_results = pd.DataFrame(selection_results)

print("Forward Feature Selection Results:")
display(selection_results)

# Selected features and their order
print("Order in which features were selected:")

for _, row in selection_results.iterrows():
    print(f"Step {int(row['Step'])}: {row['Feature']} -> Accuracy = {row['Accuracy']:.4f}")

best_step = selection_results['Accuracy'].idxmax()
best_features = selection_results.loc[:best_step, 'Feature'].tolist()
best_accuracy = selection_results.loc[best_step, 'Accuracy']

print("\nBest number of selected features:", len(best_features))
print("Best selected features:", best_features)
print("Best model accuracy:", round(best_accuracy, 4))

