"""**a. What changes are observed?**  
Samples from the majority class are removed until the two classes are balanced.

**b. Advantage and disadvantage:**  
- Advantage: It reduces the dataset size and balances the classes.
- Disadvantage: It can remove useful information from the majority class.
"""

